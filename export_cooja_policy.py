#!/usr/bin/env python3
"""Generate a six-epoch *offline replay* policy for the Cooja motes.

NOT a real-time controller: Python runs the selected protocol through the same
simulate() used for the research results, on the Cooja mote layout, and writes
policy.h before the firmware is compiled. Cooja motes then follow the schedule.

Each Cooja epoch stands for ROUNDS_PER_EPOCH model rounds; the heads replayed in
an epoch are those in force at its first round.

Usage: python export_cooja_policy.py [--policy sa|coa]
"""
import argparse
from pathlib import Path
import numpy as np
from simulator.engine import Config, assign_nodes, simulate

POSITIONS = np.asarray([
    [18,22], [35,28], [65,15], [83,43],
    [14,73], [39,79], [67,68], [88,84]
],dtype=float)
INITIAL_ENERGY = np.array([.5, .7, .5, 1., .5, 1., .5, .7], dtype=float)
EPOCHS = 6
ROUNDS_PER_EPOCH = 200
POLICIES = {'sa': 'COA-APSO-LEACH-SA', 'coa': 'COA-APSO-LEACH'}


def cooja_config():
    return Config(nodes=len(POSITIONS), rounds=EPOCHS*ROUNDS_PER_EPOCH, area=100., seed=123,
                  clusters=3, pso_particles=10, pso_iterations=18, bs_x=50, bs_y=50,
                  lookahead=30, hybrid_routing=True)


def schedule(protocol):
    """Return per-epoch head lists (0-based) and the run summary."""
    run = simulate(cooja_config(), protocol, capture=True, layout=(POSITIONS, INITIAL_ENERGY))
    changes = run['changes']
    heads = [np.asarray([c for c in changes if c['round'] <= e*ROUNDS_PER_EPOCH][-1]['heads'])
             for e in range(EPOCHS)]
    return heads, run['summary']


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--policy', choices=POLICIES, default='sa')
    protocol = POLICIES[ap.parse_args().policy]
    heads, summary = schedule(protocol)
    every_mote = np.ones(len(POSITIONS), dtype=bool)  # all Cooja motes stay powered
    assignments = [[int(a+2) for a in assign_nodes(POSITIONS, every_mote, h)] for h in heads]
    data = '\n'.join('  {'+','.join(str(i) for i in row)+'},' for row in assignments)
    header=f'''#ifndef COA_POLICY_H
#define COA_POLICY_H
#include <stdint.h>
#define COA_EPOCHS {EPOCHS}
#define COA_POLICY_NAME "{protocol}"
/* Generated by export_cooja_policy.py; node IDs 2..9; {ROUNDS_PER_EPOCH} model rounds per epoch. */
static const uint8_t COA_ASSIGNMENT[COA_EPOCHS][8] = {{
{data}
}};
#endif
'''
    dest=Path(__file__).parent/'cooja'/'policy.h'
    dest.write_text(header)
    print(f'Generated {dest} using {protocol}')
    previous = None
    for epoch, h in enumerate(heads):
        ids = sorted(int(x)+2 for x in h)
        print(f' epoch {epoch} | changed={previous is not None and ids != previous} | heads={ids}')
        previous = ids
    print(f" model: {summary['reconfigurations']} reconfigurations, {summary['reconfigs_rejected']} rejected, "
          f"first node death={summary['fnd'] or 'none'} within {EPOCHS*ROUNDS_PER_EPOCH} rounds")

if __name__=='__main__':main()
